/** Interpola {placeholders} en un mensaje del catálogo. */
export function interpolate(msg: string, params?: Record<string, string | number>): string {
  if (!params) return msg;
  return msg.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

export function makeT<K extends string>(catalog: Record<Idioma, Record<K, string>>, idioma: Idioma) {
  return (key: K, params?: Record<string, string | number>) =>
    interpolate(catalog[idioma][key] ?? catalog.es[key] ?? key, params);
}
