/** Label de una categoría: usa el catálogo si existe, si no el texto tal cual. */
export function categoryLabel(categoria: string | undefined, idioma: Idioma): string {
  if (!categoria) return '';
  return conversationCategoryLabels[idioma][categoria] ?? categoria;
}

